//! Where mail domains keep their servers.
//!
//! A table compiled from public settings, carried here rather than asked for over the network: a
//! person types an address and something has to know which machine holds the mail. Asking would
//! tell somebody else that this person uses this domain, before any consent, in a product whose
//! thesis is that mail stays with the person. A quarter of a megabyte tells nobody anything.
//!
//! Sorted by domain, and the lookup depends on that. A provider with no IMAP server is left out:
//! this build reads mail over IMAP, so carrying one would be an answer that fails at the first
//! connection rather than at the first question.
//!

